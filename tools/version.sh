# This script generates tools/maui_libs/version.py based on git information and VERSION file.

set -e

# Change to the tools directory
cd "$(dirname "$0")"

# Read version from VERSION file
if [ -f "VERSION" ]; then
    MAJOR=$(grep "MAJOR=" VERSION | cut -d'=' -f2)
    MINOR=$(grep "MINOR=" VERSION | cut -d'=' -f2)
    PATCH=$(grep "PATCH=" VERSION | cut -d'=' -f2)
else
    MAJOR=0
    MINOR=0
    PATCH=0
fi

# Get git info
if git rev-parse --git-dir > /dev/null 2>&1; then
    GIT_COMMIT_COUNT=$(git rev-list --count HEAD)
    GIT_SHORT_HASH=$(git rev-parse --short HEAD)
    GIT_DIRTY=$(git diff --quiet || echo "-dirty")
else
    GIT_COMMIT_COUNT=0
    GIT_SHORT_HASH="unknown"
    GIT_DIRTY=""
fi

FULL_VERSION="${MAJOR}.${MINOR}.${PATCH}-${GIT_COMMIT_COUNT}-${GIT_SHORT_HASH}${GIT_DIRTY}"

# Write to python file
cat << EOF > maui_libs/version.py
# Copyright 2026 The ChromiumOS Authors
# Use of this source code is governed by a BSD-style license that can be
# found in the LICENSE file.

# Automatically generated by version.sh. Do not edit.
__version__ = "${FULL_VERSION}"
EOF
